/**
 * This filter is responsible for rendering the resource urls generated by
 * the desktop.
 *
 * We have a resources directory that contains all the portal resources.
 * Under this directory, we have (optiopnally) a directory per reseller where
 * each reseller can override the generic resource.
 *
 * Example:
 * --- resources/
 *     + logo.gif
 *     + scripts.js
 *     ---- reseller1
 *          + logo.gif
 *     ---- reseller2
 *          + logo.gif
 *
 * We don't want the desktop to know about our file structure or about the
 * fact that a reseller might want to customize some resources.
 *
 * When the desktop needs a resource (gifs, javascript, etc.) stored on the
 * portal, it uses urls following the pattern /x-res/<path to the resource>.
 * Example:
 * <img src="/x-res/logo.gif"/>
 * This filter traps such urls and map them to the actual resource url. It first
 * tries to locate the resource in the reseller's directory, and then in the
 * generic directory.
 *
 */
public class ResourceFilter implements Filter
 {
  /** The class's logger */
  private static Log m_log = LogFactory.getLog(ResourceFilter.class);

  private FilterConfig config = null;
  private ServletContext ctx = null;

  public void init(FilterConfig filterConfig) throws ServletException
  {
    this.config = filterConfig;
  }


  public void destroy()
  {
    config = null;
  }


  public void doFilter(ServletRequest servletRequest,
                       ServletResponse servletResponse,
                       FilterChain filterChain) throws IOException, ServletException
  {
    boolean stopHere = false;
    // Initialize the context if required
    if (ctx == null) {
      ctx = config.getServletContext();
    }
    // process the request
    if (servletRequest instanceof HttpServletRequest) {
      HttpServletRequest request = (HttpServletRequest) servletRequest;
      HttpServletResponse response = (HttpServletResponse) servletResponse;
      if (ResourceManager.isResourceRequest(request)){
        stopHere = true;
        InputStream resourceStream;
        boolean localized = false;
        resourceStream = ResourceManager.getStaticResourceAsStream(request,localized);
        if (resourceStream != null){
          //m_log.debug("Found requested resource: " + request.getRequestURI());
          byte[] buff = new byte[256];
          int nbBytes = 0;
          while ((nbBytes = resourceStream.read(buff)) != -1){
            servletResponse.getOutputStream().write(buff,0,nbBytes);
          }
          resourceStream.close();
          servletResponse.flushBuffer();
        } else {
          m_log.warn("Could not find requested resource: " + request.getRequestURI());
          response.setStatus(HttpServletResponse.SC_NOT_FOUND);
        }

      }
    }

    // If this is not a request for a resource, we continue with the next filter
    if (!stopHere) {
      filterChain.doFilter(servletRequest, servletResponse);
    }
  }


}